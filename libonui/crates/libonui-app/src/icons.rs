/// Look up an icon by an app id, so screens do not need a match of their own.
pub fn for_app(app_id: &str) -> &'static Icon {
    match app_id {
        "firefox" => &GLOBE,
        "files" => &FOLDER,
        "terminal" => &TERMINAL,
        "store" => &BAG,
        "settings" => &SLIDERS,
        "text-editor" => &NOTE,
        "photos" => &IMAGE,
        "video" => &PLAY,
        "music" => &MUSIC,
        "mail" => &MAIL,
        "archive-manager" => &ARCHIVE,
        "screenshot" => &CAMERA,
        "software-update" => &DOWNLOAD,
        "disks" => &DISK,
        "calculator" => &CALC,
        "help" => &HELP,
        _ => &GRID,
    }
}

impl Icon {
    /// Draw the icon inside `rect`, centred, using the palette's ink colour.
    pub fn draw(&self, ui: &Ui, rect: egui::Rect, color: Color32, stroke_w: f32) {
        let size = rect.width().min(rect.height());
        let scale = size / 24.0;
        let origin = rect.center() - Vec2::splat(size / 2.0);
        let map =
            |(x, y): (f32, f32)| -> Pos2 { Pos2::new(origin.x + x * scale, origin.y + y * scale) };
        let stroke = Stroke::new((stroke_w * scale.max(0.7)).max(1.0), color);
        let painter = ui.painter();

        for polyline in self.strokes {
            if polyline.len() < 2 {
                continue;
            }
            let points: Vec<Pos2> = polyline.iter().map(|p| map(*p)).collect();
            painter.add(Shape::line(points, stroke));
        }
        for (cx, cy, r) in self.dots {
            painter.circle_filled(map((*cx, *cy)), r * scale, color);
        }
    }

    /// Draw into a layout-allocated square of `size` pixels.
    pub fn show(&self, ui: &mut Ui, size: f32, color: Color32) {
        let (rect, _) = ui.allocate_exact_size(Vec2::splat(size), Sense::hover());
        self.draw(ui, rect, color, 1.7);
    }

    /// Draw inside an existing rectangle without allocating.
    pub fn paint(&self, ui: &Ui, rect: egui::Rect, color: Color32, stroke_w: f32) {
        self.draw(ui, rect, color, stroke_w);
    }
}
