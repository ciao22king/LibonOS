//! An authored icon set.
//!
//! Icons are drawn as vector geometry in one consistent stroke and weight, in
//! the spirit of the craft floor's rule that emoji and Unicode glyphs never
//! stand in for an icon system. Each icon is a set of line segments in a
//! 24×24 box, scaled to whatever size the caller needs.

use egui::{Color32, Pos2, Sense, Shape, Stroke, Ui, Vec2};

/// One icon: polylines in a 24×24 coordinate box.
pub struct Icon {
    strokes: &'static [&'static [(f32, f32)]],
    /// Optional filled dot, for a state marker.
    dots: &'static [(f32, f32, f32)],
}

const fn icon(strokes: &'static [&'static [(f32, f32)]], dots: &'static [(f32, f32, f32)]) -> Icon {
    Icon { strokes, dots }
}

